CREATE TABLE category (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(60) NOT NULL,
    display_order INT         NOT NULL DEFAULT 0,
    CONSTRAINT uk_category_name UNIQUE (name)
);

CREATE TABLE menu_item (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(100)  NOT NULL,
    description    VARCHAR(500)  NOT NULL DEFAULT '',
    price          NUMERIC(10,2) NOT NULL,
    image_filename VARCHAR(100),
    available      BOOLEAN       NOT NULL DEFAULT TRUE,
    featured       BOOLEAN       NOT NULL DEFAULT FALSE,
    category_id    BIGINT        NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_menu_item_category FOREIGN KEY (category_id) REFERENCES category (id),
    CONSTRAINT ck_menu_item_price CHECK (price >= 0)
);

CREATE INDEX idx_menu_item_category ON menu_item (category_id);
CREATE INDEX idx_menu_item_available ON menu_item (available);

CREATE TABLE admin_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(60)  NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    CONSTRAINT uk_admin_username UNIQUE (username)
);
