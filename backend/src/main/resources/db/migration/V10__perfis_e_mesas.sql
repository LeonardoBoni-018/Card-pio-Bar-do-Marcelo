-- Faixa V10–V19 reservada ao módulo de comandas (ver docs/comandas/ESCOPO.md).

-- Usuários: o proprietário existente vira ADMIN; garçons são GARCOM.
ALTER TABLE admin_user ADD COLUMN display_name VARCHAR(60) NOT NULL DEFAULT 'Proprietário';
ALTER TABLE admin_user ADD COLUMN role VARCHAR(10) NOT NULL DEFAULT 'ADMIN';
ALTER TABLE admin_user ADD COLUMN active BOOLEAN NOT NULL DEFAULT TRUE;
ALTER TABLE admin_user ADD CONSTRAINT ck_admin_user_role CHECK (role IN ('ADMIN', 'GARCOM'));

-- Mesas cadastradas pelo proprietário.
CREATE TABLE dining_table (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(40) NOT NULL,
    display_order INT         NOT NULL DEFAULT 0,
    active        BOOLEAN     NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_dining_table_name UNIQUE (name)
);
