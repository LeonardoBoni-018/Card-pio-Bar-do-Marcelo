-- Comandas (etapa 2). Só ADICIONA estrutura. Valores em NUMERIC; nome e preço do item são COPIADOS no lançamento.

CREATE TABLE comanda (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_id    BIGINT        NOT NULL,
    label       VARCHAR(40),
    status      VARCHAR(10)   NOT NULL DEFAULT 'OPEN',
    people      INT,
    discount    NUMERIC(10,2) NOT NULL DEFAULT 0,
    total       NUMERIC(10,2),
    merged_into BIGINT,
    opened_by   BIGINT        NOT NULL,
    opened_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    closed_by   BIGINT,
    closed_at   TIMESTAMP WITH TIME ZONE,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    version     BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT fk_comanda_table  FOREIGN KEY (table_id)  REFERENCES dining_table (id),
    CONSTRAINT fk_comanda_opened FOREIGN KEY (opened_by) REFERENCES admin_user (id),
    CONSTRAINT fk_comanda_closed FOREIGN KEY (closed_by) REFERENCES admin_user (id),
    CONSTRAINT fk_comanda_merged FOREIGN KEY (merged_into) REFERENCES comanda (id),
    CONSTRAINT ck_comanda_status CHECK (status IN ('OPEN', 'CLOSED', 'CANCELED', 'MERGED')),
    CONSTRAINT ck_comanda_people CHECK (people IS NULL OR people >= 1),
    CONSTRAINT ck_comanda_discount CHECK (discount >= 0)
);

CREATE INDEX idx_comanda_status ON comanda (status);
CREATE INDEX idx_comanda_table ON comanda (table_id);
CREATE INDEX idx_comanda_closed_at ON comanda (closed_at);

CREATE TABLE comanda_item (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comanda_id   BIGINT        NOT NULL,
    menu_item_id BIGINT,
    name         VARCHAR(100)  NOT NULL,
    unit_price   NUMERIC(10,2) NOT NULL,
    price_unit   VARCHAR(4)    NOT NULL DEFAULT 'UNIT',
    quantity     NUMERIC(10,3) NOT NULL,
    note         VARCHAR(140),
    custom       BOOLEAN       NOT NULL DEFAULT FALSE,
    added_by     BIGINT        NOT NULL,
    added_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_comanda_item_comanda FOREIGN KEY (comanda_id) REFERENCES comanda (id) ON DELETE CASCADE,
    -- produto excluído do cardápio depois: a linha da comanda fica (com nome e preço copiados)
    CONSTRAINT fk_comanda_item_menu FOREIGN KEY (menu_item_id) REFERENCES menu_item (id) ON DELETE SET NULL,
    CONSTRAINT fk_comanda_item_user FOREIGN KEY (added_by) REFERENCES admin_user (id),
    CONSTRAINT ck_comanda_item_price CHECK (unit_price >= 0),
    CONSTRAINT ck_comanda_item_qty CHECK (quantity > 0),
    CONSTRAINT ck_comanda_item_unit CHECK (price_unit IN ('UNIT', 'KG'))
);

CREATE INDEX idx_comanda_item_comanda ON comanda_item (comanda_id);
CREATE INDEX idx_comanda_item_menu ON comanda_item (menu_item_id);
